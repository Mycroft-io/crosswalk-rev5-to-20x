// Precompiles FedRAMP's JSON Schemas to plain validation functions (no eval at runtime,
// so the page works under a strict Content-Security-Policy).
import fs from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
const ref = JSON.parse(fs.readFileSync('data/reference.json', 'utf8'));
const ajv = new Ajv2020.default({ allErrors: true, strict: false, code: { source: true, esm: true }, schemas: Object.values(ref.schemas) });
addFormats.default(ajv);
const kinds = { cpo: 'certification-package-overview', sdr: 'security-decision-record', ocr: 'ongoing-certification-report',
  vdr: 'vulnerability-detail-report', avi: 'accepted-vulnerability-info', hist: 'historical-ver-activity' };
const map = Object.fromEntries(Object.entries(kinds).map(([k, n]) => [k, `https://fedramp.gov/schemas/fedramp-${n}-schema-2026-06-24.json`]));
fs.writeFileSync('src/validators.gen.js', '// Generated by build/gen-validators.mjs. Do not edit.\n' + standaloneCode.default(ajv, map));
console.log('validators', fs.statSync('src/validators.gen.js').size);
